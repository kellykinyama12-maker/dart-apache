// Regenerates lib/src/framework/live/runtime.dart from the client runtime JS,
// so the Dartisan Live runtime can be inlined by apps without shipping an asset.
//
// Run after editing public/app/dartisan-live.js:
//   dart run tool/gen_live_runtime.dart
import 'dart:io';

void main() {
  final js = File('public/app/dartisan-live.js').readAsStringSync();
  if (js.contains("'''")) {
    stderr.writeln("runtime JS contains ''' — cannot embed as a raw string");
    exitCode = 1;
    return;
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_live_runtime.dart from '
        'public/app/dartisan-live.js.')
    ..writeln('// Do not edit by hand; rerun the generator to update.')
    ..writeln()
    ..writeln('/// The Dartisan Live client runtime (JavaScript), embedded so '
        'apps can inline')
    ..writeln('/// it via `liveMount(inlineRuntime: liveRuntimeSource)` without '
        'shipping an asset.')
    ..writeln("const String liveRuntimeSource = r'''")
    ..write(js)
    ..writeln("''';");
  File('lib/src/framework/live/runtime.dart').writeAsStringSync(out.toString());
  stdout.writeln('wrote lib/src/framework/live/runtime.dart '
      '(${js.length} chars embedded)');
}
